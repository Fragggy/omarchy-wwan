const assert = require('node:assert/strict')
const model = require('../Model.js')

assert.deepEqual(model.parseTabValues('state\tregistered\nsignal\t92\n'), { state: 'registered', signal: '92' })
assert.equal(model.connected({ profile_state: 'activated' }), true)
assert.equal(model.connected({ profile_state: '' }), false)
assert.equal(model.formatRate(1536), '1.50 KB/s')
assert.equal(model.signalIcon(91, 'registered', false), '󰤨')
const rates = model.nextRates({ iface: 'wwan0', rx: 100, tx: 50, time: 1000 }, { iface: 'wwan0', rx_bytes: '1100', tx_bytes: '550' }, 2000)
assert.equal(rates.download, 1000)
assert.equal(rates.upload, 500)
const reset = model.nextRates(rates, { iface: 'wwan1', rx_bytes: '10', tx_bytes: '20' }, 3000)
assert.equal(reset.download, 0)
assert.equal(reset.upload, 0)
console.log('Model tests passed')
